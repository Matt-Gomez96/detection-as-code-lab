"""Convert Sigma rules to Splunk SPL.

Each rule ``rules/**/<name>.yml`` produces ``splunk/<name>.spl``. The ``.spl``
files are committed so they can be reviewed in pull requests; a test fails if
they are out of date (run ``uv run detlab convert`` to regenerate them).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from sigma.backends.splunk import SplunkBackend

from detlab.engine import load_rule
from detlab.pipelines import splunk_pipeline

HEADER = "``` Generated by detlab from {source} - do not edit by hand ```"


def to_splunk(rule_path: str | Path) -> list[str]:
    backend = SplunkBackend(processing_pipeline=splunk_pipeline())
    return backend.convert(load_rule(rule_path))


def render(rule_path: Path, root: Path) -> str:
    """Full content of the ``.spl`` file for one rule (header comment + queries)."""
    source = rule_path.relative_to(root).as_posix()
    lines = [HEADER.format(source=source), *to_splunk(rule_path)]
    return "\n".join(lines) + "\n"


def rule_files(root: Path) -> list[Path]:
    return sorted((root / "rules").rglob("*.yml"))


@dataclass
class Result:
    written: list[Path]
    outdated: list[Path]
    stale: list[Path]


def convert_all(root: Path, check: bool = False) -> Result:
    """Generate ``splunk/*.spl`` for every rule. With ``check=True`` only report differences."""
    out_dir = root / "splunk"
    expected: dict[Path, str] = {
        out_dir / f"{rule.stem}.spl": render(rule, root) for rule in rule_files(root)
    }
    outdated = [
        path
        for path, content in expected.items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]
    existing = set(out_dir.glob("*.spl")) if out_dir.exists() else set()
    stale = sorted(existing - set(expected))

    if check:
        return Result(written=[], outdated=outdated, stale=stale)

    out_dir.mkdir(exist_ok=True)
    for path in outdated:
        path.write_text(expected[path], encoding="utf-8", newline="\n")
    for path in stale:
        path.unlink()
    return Result(written=outdated, outdated=[], stale=stale)
